import { createHash } from "node:crypto";
import { slugifyName } from "./asset-slug";
import { canonicalMarketName } from "./market-identity";

/**
 * Public URL identity for an OBSERVED asset.
 *
 * An observed asset exists in `provider_assets` — currently 39,999 distinct
 * canonical names — but has no row in the 150-row `assets` table, so it has no
 * FloatAlpha UUID and cannot use the analysed slug contract.
 *
 * ## Same shape, different discriminator
 *
 *   analysed   /asset/ak-47-redline-field-tested-f75f1e81        8 hex of a UUID
 *   observed   /observed/ak-47-redline-field-tested-6ea9b71d44ad 12 hex of a name hash
 *
 * The readable portion is generated by the same `slugifyName` the analysed
 * contract uses, so the two read alike. The discriminator differs in both
 * source and length, which is what keeps the namespaces unambiguous even
 * though both are hex.
 *
 * ## Why a discriminator is unavoidable
 *
 * `slugifyName` strips every non-ASCII character, and 61 groups covering 144
 * production names collide once it has. The clearest case is a pair of real
 * items:
 *
 *   Desert Eagle | Sunset Storm 壱 (Factory New)   ┐ both slugify to
 *   Desert Eagle | Sunset Storm 弐 (Factory New)   ┘ desert-eagle-sunset-storm-factory-new
 *
 * 壱 and 弐 are Japanese one and two. A further 290 names reach the 60-character
 * readable cap and are truncated into each other's space.
 *
 * ## Why twelve hex and not eight
 *
 * Eight hex is 32 bits. Over 39,999 names the birthday expectation of a
 * collision is about 0.19 — we measured zero, which is luck rather than
 * safety, and the figure rises with the catalogue. Twelve hex is 48 bits and
 * puts the expectation near 3e-6, where it stays. Measured collisions over the
 * full catalogue: zero at 8, 10 and 12 hex.
 *
 * ## The hash input is the join key
 *
 * The digest is taken over `canonicalMarketName(name)` — the exact string
 * `crossVenueFor` and the inventory matcher join on. A URL therefore cannot
 * address an item the rest of the system would resolve differently.
 */

/** Hex characters of SHA-256 carried in an observed slug. */
export const OBSERVED_DISCRIMINATOR_LENGTH = 12;

/** The route namespace. Deliberately not `/asset/`. */
export const OBSERVED_ROUTE_PREFIX = "/observed";

const OBSERVED_DISCRIMINATOR = new RegExp(
  `^[0-9a-f]{${OBSERVED_DISCRIMINATOR_LENGTH}}$`,
);

/** The discriminator for a name. Canonicalised first, always. */
export function observedDiscriminator(marketHashName: string): string {
  return createHash("sha256")
    .update(canonicalMarketName(marketHashName), "utf8")
    .digest("hex")
    .slice(0, OBSERVED_DISCRIMINATOR_LENGTH);
}

/** The public path segment for an observed asset. */
export function observedSlug(marketHashName: string): string {
  const readable = slugifyName(canonicalMarketName(marketHashName));
  const discriminator = observedDiscriminator(marketHashName);
  // Every production name yields a non-empty readable portion, but a name of
  // pure punctuation would not, and a bare discriminator still resolves.
  return readable ? `${readable}-${discriminator}` : discriminator;
}

/** The public path for an observed asset. */
export function observedPath(marketHashName: string): string {
  return `${OBSERVED_ROUTE_PREFIX}/${observedSlug(marketHashName)}`;
}

/**
 * The discriminator a slug points at, or null.
 *
 * Read from the end: the readable portion may itself contain hex-looking
 * words, but the discriminator is always last. A segment of the analysed
 * length (8) is rejected here rather than guessed at, so the two namespaces
 * cannot silently accept each other's URLs.
 */
export function discriminatorFromObservedSlug(slug: string): string | null {
  const last = slug.split("-").at(-1)?.toLowerCase();
  return last && OBSERVED_DISCRIMINATOR.test(last) ? last : null;
}

/** Whether a slug is exactly the canonical spelling for this name. */
export function isCanonicalObservedSlug(
  slug: string,
  marketHashName: string,
): boolean {
  return slug === observedSlug(marketHashName);
}
